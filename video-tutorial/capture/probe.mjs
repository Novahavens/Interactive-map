import { createRequire } from "node:module";
const { chromium } = createRequire(import.meta.url)("/opt/node-tools/node_modules/playwright/index.js");
import { mock } from "./mocks.mjs";
import * as D from "./demo-data.mjs";
const BASE = "https://nova-havens-map.vercel.app";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 1, timezoneId: "America/Chicago" });
await ctx.addInitScript(() => { try { localStorage.setItem("nh-theme", "light"); localStorage.setItem("nh-reporter-name", "Will"); } catch {} });
const st = {}; await mock(ctx, st);
const p = await ctx.newPage();
const reqs = []; p.on("request", (r) => { if (r.url().includes("/api/")) reqs.push(r.method() + " " + r.url().replace(BASE, "")); });
p.on("pageerror", (e) => console.log("pageerror", e.message));
await p.goto(BASE + "/?claimId=" + D.CLAIM_ID, { waitUntil: "networkidle" });
await p.waitForTimeout(4000);
await p.screenshot({ path: "capture/probe/1-map.png" });
await p.getByRole("button", { name: new RegExp(D.hero.name) }).first().click();
await p.waitForTimeout(2500);
await p.screenshot({ path: "capture/probe/2-panel.png" });
const panel = p.locator('aside[aria-label="Property details"]:visible');
await panel.evaluate((el) => { const s = el.querySelector("[data-scroll], .overflow-y-auto") || el; s.scrollTop = 600; });
await p.waitForTimeout(800);
await p.screenshot({ path: "capture/probe/3-panel-scrolled.png" });
console.log(reqs.join("\n"));
await b.close();
